"""Authenticated encryption for third-party credentials stored in the database.

Set APP_ENCRYPTION_KEY to a Fernet key generated by:
    python -c "from cryptography.fernet import Fernet; print(Fernet.generate_key().decode())"

Keep the key in the hosting provider's secret manager. Do not commit it.
"""
from cryptography.fernet import Fernet, InvalidToken

from app.core.config import settings


PREFIX = "fernet:"


class SecretConfigurationError(RuntimeError):
    """Raised when encryption cannot safely be performed."""


def _fernet() -> Fernet:
    key = settings.app_encryption_key.strip()
    if not key:
        raise SecretConfigurationError(
            "APP_ENCRYPTION_KEY must be configured before saving site credentials"
        )
    try:
        return Fernet(key.encode("ascii"))
    except (ValueError, UnicodeEncodeError):
        raise SecretConfigurationError(
            "APP_ENCRYPTION_KEY must be a valid Fernet key"
        ) from None


def encrypt_secret(value: str) -> str:
    if not value:
        return ""
    if value.startswith(PREFIX):
        # Avoid accidentally encrypting the same value twice.
        decrypt_secret(value)
        return value
    encrypted = _fernet().encrypt(value.encode("utf-8")).decode("ascii")
    return PREFIX + encrypted


def decrypt_secret(value: str) -> str:
    if not value:
        return ""
    if not value.startswith(PREFIX):
        # Backward compatibility for credentials saved before encryption was added.
        # Migrate these legacy plaintext rows after APP_ENCRYPTION_KEY is configured.
        return value
    token = value[len(PREFIX):]
    try:
        return _fernet().decrypt(token.encode("ascii")).decode("utf-8")
    except InvalidToken:
        raise SecretConfigurationError(
            "Stored credential cannot be decrypted; verify APP_ENCRYPTION_KEY"
        ) from None
    except (ValueError, UnicodeEncodeError):
        raise SecretConfigurationError(
            "Stored credential has an invalid encrypted format"
        ) from None
